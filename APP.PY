import os
import sqlite3

import pandas as pd
import streamlit as st

from build_sqlite import DB_PATH, build

st.set_page_config(page_title="RetailSphere", page_icon="🛒", layout="wide")


@st.cache_resource
def get_conn():
    # If the .db file is missing (e.g. not committed), build it once.
    if not os.path.exists(DB_PATH):
        with st.spinner("Building database (one time, ~10 seconds)..."):
            build(DB_PATH)
    return sqlite3.connect(DB_PATH, check_same_thread=False)


@st.cache_data
def run(sql: str) -> pd.DataFrame:
    return pd.read_sql_query(sql, get_conn())


# MySQL -> SQLite: DATEDIFF(NOW(), x) -> julianday('now') - julianday(x)
#                  DATE_FORMAT(x,'%Y-%m') -> strftime('%Y-%m', x)
QUERIES = {
    "1. RFM Segmentation": (
        "Top 20 customers by money spent (delivered orders). Tier: Gold > 5L, Silver > 1L, else Bronze.",
        """SELECT customer_id,
       CAST(julianday('now') - julianday(MAX(order_date)) AS INTEGER) AS recency_days,
       COUNT(order_id) AS frequency,
       ROUND(SUM(total_amount), 2) AS monetary,
       CASE WHEN SUM(total_amount) > 500000 THEN 'Gold'
            WHEN SUM(total_amount) > 100000 THEN 'Silver'
            ELSE 'Bronze' END AS customer_tier
FROM orders
WHERE status = 'delivered'
GROUP BY customer_id
ORDER BY monetary DESC
LIMIT 20""", ("customer_id", "monetary", "bar")),
    "2. Monthly Revenue": (
        "Revenue, order count and average order value per month.",
        """SELECT strftime('%Y-%m', order_date) AS month,
       COUNT(order_id) AS total_orders,
       ROUND(SUM(total_amount), 2) AS revenue,
       ROUND(AVG(total_amount), 2) AS avg_order_value
FROM orders
WHERE status = 'delivered'
GROUP BY strftime('%Y-%m', order_date)
ORDER BY month""", ("month", "revenue", "line")),
    "3. Top Products": (
        "Top 10 products by revenue (JOIN of order_items, products, categories).",
        """SELECT p.name AS product, c.name AS category,
       SUM(oi.quantity) AS units_sold,
       ROUND(SUM(oi.quantity * oi.unit_price), 2) AS total_revenue
FROM order_items oi
JOIN products p   ON oi.product_id = p.product_id
JOIN categories c ON p.category_id = c.category_id
GROUP BY p.product_id
ORDER BY total_revenue DESC
LIMIT 10""", ("product", "total_revenue", "bar")),
    "4. Low Inventory Alert": (
        "Stock below reorder level, with how many units are needed.",
        """SELECT p.name AS product, w.city AS warehouse,
       i.quantity AS current_stock, i.reorder_level,
       (i.reorder_level - i.quantity) AS units_needed
FROM inventory i
JOIN products p   ON i.product_id = p.product_id
JOIN warehouses w ON i.warehouse_id = w.warehouse_id
WHERE i.quantity < i.reorder_level
ORDER BY units_needed DESC
LIMIT 15""", ("product", "units_needed", "bar")),
    "5. Supplier Performance": (
        "Revenue generated by each supplier's products (delivered orders).",
        """SELECT s.name AS supplier, s.country,
       COUNT(DISTINCT p.product_id) AS products_supplied,
       ROUND(SUM(oi.quantity * oi.unit_price), 2) AS total_revenue_generated
FROM suppliers s
JOIN products p     ON s.supplier_id = p.supplier_id
JOIN order_items oi ON p.product_id = oi.product_id
JOIN orders o       ON oi.order_id = o.order_id
WHERE o.status = 'delivered'
GROUP BY s.supplier_id
ORDER BY total_revenue_generated DESC""", ("supplier", "total_revenue_generated", "bar")),
    "6. Running Revenue (Window Fn)": (
        "Cumulative revenue month by month using SUM(SUM(...)) OVER (ORDER BY ...).",
        """SELECT strftime('%Y-%m', order_date) AS month,
       ROUND(SUM(total_amount), 2) AS monthly_revenue,
       ROUND(SUM(SUM(total_amount)) OVER (
             ORDER BY strftime('%Y-%m', order_date)), 2) AS running_total
FROM orders
WHERE status = 'delivered'
GROUP BY strftime('%Y-%m', order_date)
ORDER BY month""", ("month", "running_total", "line")),
    "7. State-wise Sales": (
        "Customers, orders and revenue by state.",
        """SELECT c.state,
       COUNT(DISTINCT c.customer_id) AS customers,
       COUNT(o.order_id) AS orders,
       ROUND(SUM(o.total_amount), 2) AS revenue
FROM customers c
JOIN orders o ON c.customer_id = o.customer_id
WHERE o.status = 'delivered'
GROUP BY c.state
ORDER BY revenue DESC""", ("state", "revenue", "bar")),
}

st.title("🛒 RetailSphere: Retail Supply Chain Analytics")
st.caption("A Walmart-inspired relational database with SQL analytics. "
           "Data is synthetic (generated with Faker). This hosted demo runs on SQLite; "
           "the original project uses MySQL 8.")

counts = {t: int(run(f"SELECT COUNT(*) AS n FROM {t}")["n"][0])
          for t in ["customers", "orders", "order_items", "products", "inventory"]}
cols = st.columns(len(counts))
for col, (t, n) in zip(cols, counts.items()):
    col.metric(t.replace("_", " ").title(), f"{n:,}")

tabs = st.tabs(list(QUERIES.keys()))
for tab, (name, (desc, sql, (x, y, kind))) in zip(tabs, QUERIES.items()):
    with tab:
        st.subheader(name)
        st.write(desc)
        df = run(sql)
        chart_df = df.set_index(x)[y]
        if kind == "line":
            st.line_chart(chart_df)
        else:
            st.bar_chart(chart_df)
        st.dataframe(df, hide_index=True)
        with st.expander("Show SQL"):
            st.code(sql, language="sql")